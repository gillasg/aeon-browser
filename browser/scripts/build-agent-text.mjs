import { existsSync } from "node:fs";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { spawnSync } from "node:child_process";

// One source for the agent-facing text. browserkit/docs/agent/sections holds the skill's Markdown;
// this writes Aeon's skill (those sections, browserkit→aeon, plus Aeon-only parts) and the
// browser-code guidance both tools carry. Run with --check in CI to fail on stale output.

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const aeonRepo = resolve(repo, "..");
const check = process.argv.includes("--check");
const MARKDOWN_HEADER =
  "<!-- Generated by browserkit/scripts/build-agent-text.mjs from browserkit/docs/agent/sections. Do not edit; edit the sources and run pnpm agent-text. -->";
const TS_HEADER =
  "// Generated by browserkit/scripts/build-agent-text.mjs from browserkit/docs/agent/guidance.md and Aeon's guidance-extra.md. Do not edit.";

const outputs = [];
const CORE_CAP = 5000;
const PACK_CAP = 2000;
const SKILL_CAP = 12000;
const sections = await readSections(join(repo, "docs", "agent", "sections"));
const guidanceText = await read(join(repo, "docs", "agent", "guidance.md"));
const packDir = join(repo, "docs", "agent", "packs");
const packs = existsSync(packDir) ? await readSections(packDir) : new Map();
outputs.push({
  path: join(repo, "packages", "engine", "src", "agent-packs.generated.ts"),
  content: await packsSource(packs),
});
if (existsSync(join(aeonRepo, "skills", "aeon"))) {
  const parts = await readSections(join(aeonRepo, "skills", "aeon", "parts"));
  const aeonSkill = assemble([
    parts.get("frontmatter"),
    MARKDOWN_HEADER,
    parts.get("00-intro"),
    guidanceText,
    parts.get("10-handoff"),
    parts.get("30-abilities"),
    parts.get("20-routines"),
    parts.get("40-review"),
  ]);
  outputs.push({ path: join(aeonRepo, "skills", "aeon", "SKILL.md"), content: aeonSkill });
}

// browserkit's own browser_code tool description: its primer plus the same shared guidance.
{
  const primer = (await read(join(repo, "docs", "agent", "primer-browserkit.md"))).trim();
  const shared = split(await read(join(repo, "docs", "agent", "guidance.md")));
  const descriptionPath = join(repo, "apps", "bridge", "src", "guidance.ts");
  const source = [
    "// Generated by browserkit/scripts/build-agent-text.mjs from browserkit/docs/agent (primer-browserkit.md and guidance.md). Do not edit.",
    "export const browserCodeDescription = [",
    ...[primer, ...shared].map((paragraph) => `  ${JSON.stringify(paragraph)},`),
    '].join("\\n\\n");',
    "",
  ].join("\n");
  outputs.push({
    path: descriptionPath,
    content: await format(source, { filepath: descriptionPath }),
  });
}

if (existsSync(join(aeonRepo, "packages", "pi-adapter"))) {
  const guidance = await guidanceSource();
  const guidancePath = join(aeonRepo, "packages", "pi-adapter", "src", "browser-code-guidance.ts");
  outputs.push({
    path: guidancePath,
    content: await format(guidance, { filepath: guidancePath }),
  });
}

const capErrors = capFailures(guidanceText, packs, outputs);
const hostErrors = await hostFailures(outputs);
for (const line of [...capErrors, ...hostErrors]) process.stderr.write(`${line}\n`);
if (capErrors.length || hostErrors.length) process.exit(1);

let stale = 0;
for (const output of outputs) {
  let current = "";
  try {
    current = await readFile(output.path, "utf8");
  } catch {
    // Missing is stale too.
  }
  if (current === output.content) continue;
  stale += 1;
  if (check) process.stderr.write(`stale: ${output.path}\n`);
  else {
    await writeFile(output.path, output.content);
    process.stdout.write(`wrote ${output.path}\n`);
  }
}
if (check && stale) {
  process.stderr.write("Agent text is stale. Run `pnpm agent-text` in browserkit.\n");
  process.exit(1);
}

const footprint = spawnSync(process.execPath, [join(repo, "scripts", "agent-text-footprint.mjs")], {
  stdio: "inherit",
});
if (footprint.status) process.exit(footprint.status);

async function readSections(folder) {
  const map = new Map();
  for (const file of (await readdir(folder)).filter((name) => name.endsWith(".md")).sort())
    map.set(file.replace(/\.md$/, ""), await read(join(folder, file)));
  return map;
}

function commonSections(sections) {
  return ["02-which-way", "03-browser-code", "04-reading", "05-forms", "06-signin"]
    .map((name) => sections.get(name))
    .concat(
      ["07-blocked", "08-sites", "09-sessions", "10-habits", "11-pack", "12-providers"].map(
        (name) => sections.get(name),
      ),
    );
}

function rewriteForAeon(text) {
  return text
    .replaceAll("{{workspace}}", "`%LOCALAPPDATA%\\Aeon\\data\\external\\<session>` on Windows")
    .replaceAll("browserkit", "aeon")
    .replaceAll("aeon's", "Aeon's");
}

function assemble(parts) {
  const text = parts
    .filter((part) => part !== undefined)
    .map((part) => part.trim())
    .filter(Boolean)
    .join("\n\n");
  return text + "\n";
}

async function read(path) {
  return readFile(path, "utf8");
}

async function guidanceSource() {
  const shared = split(await read(join(repo, "docs", "agent", "guidance.md")));
  const extra = split(await read(join(aeonRepo, "packages", "pi-adapter", "guidance-extra.md")));
  const paragraphs = [...shared];
  paragraphs[0] = `${paragraphs[0]}\n${extra[0] ?? ""}`.trim();
  const primer = extra[1] ?? "";
  // The one-line browser_code description is browserkit's primer, so both tools open the same way.
  const summary = (await read(join(repo, "docs", "agent", "primer-browserkit.md"))).trim();
  return [
    TS_HEADER,
    `export const browserRuntimePrimer = ${JSON.stringify(primer)};`,
    "",
    `export const browserCodeSummary = ${JSON.stringify(summary)};`,
    "",
    "export const browserCodeGuidelines = [",
    ...paragraphs.map((paragraph) => `  ${JSON.stringify(paragraph)},`),
    "];",
    "",
  ].join("\n");
}

async function packsSource(packMap) {
  const entries = [...packMap.entries()].sort(([left], [right]) => left.localeCompare(right));
  const body = entries
    .map(([name, text]) => `  ${JSON.stringify(name)}: ${JSON.stringify(text.trim())},`)
    .join("\n");
  const source = [
    "// Generated by browser/scripts/build-agent-text.mjs from browser/docs/agent/packs. Do not edit.",
    "export const PACKS: Record<string, string> = {",
    body,
    "};",
    "",
  ].join("\n");
  const path = join(repo, "packages", "engine", "src", "agent-packs.generated.ts");
  return format(source, { filepath: path });
}

function capFailures(guidance, packMap, built) {
  const failures = [];
  const guidanceBytes = Buffer.byteLength(guidance);
  if (guidanceBytes > CORE_CAP)
    failures.push(`core guidance is ${guidanceBytes} bytes; the cap is ${CORE_CAP}`);
  for (const [name, text] of packMap) {
    const bytes = Buffer.byteLength(text.trim());
    if (bytes > PACK_CAP) failures.push(`pack ${name} is ${bytes} bytes; the cap is ${PACK_CAP}`);
  }
  const skill = built.find((output) => output.path.endsWith("SKILL.md"));
  if (skill) {
    const bytes = Buffer.byteLength(skill.content);
    if (bytes > SKILL_CAP) failures.push(`SKILL.md is ${bytes} bytes; the cap is ${SKILL_CAP}`);
  }
  return failures;
}

async function hostFailures(built) {
  const dir = evalTaskDir();
  if (!dir) return [];
  const hosts = await evalHosts(dir);
  const files = await alwaysOnFiles();
  const failures = [];
  for (const file of files) {
    const text = await read(file.path);
    for (const host of hosts) {
      if (!hostIn(text, host)) continue;
      failures.push(`${file.path} contains eval host ${host}`);
    }
  }
  for (const output of built) {
    if (!output.path.endsWith("SKILL.md")) continue;
    for (const host of hosts) {
      if (!hostIn(output.content, host)) continue;
      failures.push(`SKILL.md contains eval host ${host}`);
    }
  }
  return failures;
}

function evalTaskDir() {
  const fromEnv = process.env.AEON_EVAL_TASKS;
  if (fromEnv && existsSync(fromEnv)) return fromEnv;
  const sibling = resolve(aeonRepo, "../aeon-eval/tasks");
  return existsSync(sibling) ? sibling : "";
}

async function alwaysOnFiles() {
  const files = [
    { path: join(repo, "docs", "agent", "guidance.md") },
    { path: join(repo, "docs", "agent", "primer-browserkit.md") },
    { path: join(aeonRepo, "packages", "pi-adapter", "guidance-extra.md") },
  ];
  if (existsSync(packDir)) {
    for (const name of [...packs.keys()]) files.push({ path: join(packDir, `${name}.md`) });
  }
  const parts = join(aeonRepo, "skills", "aeon", "parts");
  if (existsSync(parts)) {
    for (const name of await readdir(parts)) files.push({ path: join(parts, name) });
  }
  return files;
}

async function evalHosts(dir) {
  const hosts = new Set();
  for (const file of await yamlFiles(dir)) {
    const text = await read(file);
    for (const match of text.matchAll(/^\s*url:\s*['"]?([^'"\s#]+)/gm)) {
      const host = hostOf(match[1] ?? "");
      if (host) hosts.add(host);
    }
  }
  return [...hosts];
}

async function yamlFiles(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await yamlFiles(path)));
    else if (entry.name.endsWith(".yaml") || entry.name.endsWith(".yml")) found.push(path);
  }
  return found;
}

function hostOf(value) {
  if (!value || value.includes("{{") || value.includes("}}")) return "";
  const bare =
    value
      .replace(/^[a-z]+:\/\//i, "")
      .split("/")[0]
      ?.split(":")[0] ?? "";
  const host = bare.toLowerCase().replace(/^www\./, "");
  return host.includes(".") ? host : "";
}

function hostIn(text, host) {
  const escaped = host.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(?:^|[^a-z0-9.-])${escaped}(?:[^a-z0-9.-]|$)`, "i").test(text);
}

function split(text) {
  return text
    .split(/^\s*---\s*$/m)
    .map((part) => part.trim())
    .filter(Boolean);
}
